#!/usr/bin/env python3
"""A tiny real CPU experiment showing portable Raven instrumentation."""
from __future__ import annotations

import argparse
import contextlib
import json
import math
import os
from pathlib import Path
import re
import sys
import time
import traceback
import uuid

from reporting import begin_run, finish_run, write_metric


def _slurm_resources(env):
    """Read only explicit, representable scheduler allocation/request values.

    Unknown counts stay absent. Slurm memory environment variables use MiB;
    mem_bytes describes the requested total, not measured usage or a hard limit.
    """
    result = {}
    for source, target in (("SLURM_JOB_PARTITION", "partition"), ("SLURM_JOB_ACCOUNT", "account"),
                           ("SLURM_JOB_QOS", "qos")):
        if env.get(source):
            result[target] = env[source]
    raw_nodes = env.get("SLURM_JOB_NUM_NODES", env.get("SLURM_NNODES", ""))
    if re.fullmatch(r"[1-9][0-9]{0,8}", raw_nodes):
        result["nodes"] = int(raw_nodes)
    raw_cpu = env.get("SLURM_JOB_CPUS_PER_NODE", "")
    if len(raw_cpu) <= 1024 and raw_cpu:
        pieces, count, cpus = raw_cpu.split(","), 0, 0
        for piece in pieces:
            match = re.fullmatch(r"([1-9][0-9]{0,8})(?:\(x([1-9][0-9]{0,8})\))?", piece)
            if match is None:
                break
            repetitions = int(match.group(2) or 1)
            count += repetitions
            cpus += int(match.group(1)) * repetitions
        else:
            if cpus <= (1 << 63) - 1 and ("nodes" not in result or result["nodes"] == count):
                result["cpus"] = cpus
                result.setdefault("nodes", count)
    raw_gpu = env.get("SLURM_GPUS", "")
    if re.fullmatch(r"[0-9]{1,9}", raw_gpu):
        result["gpus"] = int(raw_gpu)
    # No type is inferred from CUDA_VISIBLE_DEVICES or local device numbering.
    per_node, per_cpu = env.get("SLURM_MEM_PER_NODE", ""), env.get("SLURM_MEM_PER_CPU", "")
    if not (per_node and per_cpu):  # conflicting request scopes remain unknown
        if re.fullmatch(r"[1-9][0-9]{0,12}", per_node) and "nodes" in result:
            total = int(per_node) * result["nodes"] * 1024**2
            if total <= (1 << 63) - 1:
                result["mem_bytes"] = total
        elif re.fullmatch(r"[1-9][0-9]{0,12}", per_cpu) and "cpus" in result:
            total = int(per_cpu) * result["cpus"] * 1024**2
            if total <= (1 << 63) - 1:
                result["mem_bytes"] = total
    return result


def _job_id(env):
    array, task = env.get("SLURM_ARRAY_JOB_ID"), env.get("SLURM_ARRAY_TASK_ID")
    return f"{array}_{task}" if array and task else env.get("SLURM_JOB_ID")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-id", help="unique attempt directory; generated by default")
    parser.add_argument("--experiment-id", default="pi-series")
    parser.add_argument("--attempt", type=int, default=1)
    parser.add_argument("--steps", type=int, default=20)
    parser.add_argument("--terms-per-step", type=int, default=1000)
    parser.add_argument("--slurm", action="store_true", help="read known Slurm environment fields")
    args = parser.parse_args(argv)
    if args.steps < 1 or args.terms_per_step < 1 or args.steps * args.terms_per_step > 10_000_000:
        parser.error("choose positive steps and terms-per-step, with at most 10 million terms")
    root = Path(__file__).absolute().parent
    job_id = _job_id(os.environ) if args.slurm else None
    run_id = args.run_id or f"{time.strftime('%Y%m%dT%H%M%SZ', time.gmtime())}-{uuid.uuid4().hex[:12]}"
    run_dir = begin_run(root, run_id, name="pi-series", script="experiment.py",
                        experiment_id=args.experiment_id, attempt=args.attempt,
                        job_id=job_id, resources=_slurm_resources(os.environ) if args.slurm else {},
                        parameters={"kernel": "leibniz-series", "terms": args.steps * args.terms_per_step})
    started_wall, started_cpu = time.perf_counter(), time.process_time()
    state, result, code = "FAILED", {}, 1
    try:
        with (run_dir / "logs/stdout.log").open("a", encoding="utf-8") as log, contextlib.redirect_stdout(log):
            total, partial = args.steps * args.terms_per_step, 0.0
            print(f"Starting {total} terms; run_id={run_id}")
            for step in range(1, args.steps + 1):
                for term in range((step - 1) * args.terms_per_step, step * args.terms_per_step):
                    partial += (1.0 if term % 2 == 0 else -1.0) / (2 * term + 1)
                estimate = 4 * partial
                write_metric(run_dir, {"pi_estimate": estimate, "absolute_error": abs(math.pi - estimate)},
                             step=step, phase="pi-series", progress={"completed": step * args.terms_per_step,
                                                                     "total": total, "unit": "terms"})
            result = {"estimated_pi": estimate, "absolute_error": abs(math.pi - estimate), "terms": total}
            # A fresh attempt owns outputs; exclusive creation protects earlier artifacts.
            with (run_dir / "outputs/results.json").open("x", encoding="utf-8") as output:
                json.dump(result, output, allow_nan=False, indent=2)
                output.write("\n")
            print(f"Finished; estimated_pi={estimate:.12f}; absolute_error={result['absolute_error']:.8g}")
        state, code = "COMPLETED", 0
    except (Exception, KeyboardInterrupt) as exc:
        with (run_dir / "logs/stderr.log").open("a", encoding="utf-8") as log:
            traceback.print_exc(file=log)
        print(f"Run failed: see {run_dir / 'logs/stderr.log'}", file=sys.stderr)
        if isinstance(exc, KeyboardInterrupt):
            state, code = "INTERRUPTED", 130
    # The demo has one Python process, so process_time covers this coordinator.
    # Multi-process applications must separately collect and document total CPU time.
    finish_run(run_dir, state=state, runtime_seconds=time.perf_counter() - started_wall,
               cpu_seconds=time.process_time() - started_cpu, results=result, exit_code=code,
               metadata={"cpu_seconds_source": "time.process_time", "cpu_seconds_scope": "coordinator_process",
                         "runtime_seconds_source": "time.perf_counter", "runtime_seconds_scope": "instrumented_workload"})
    print(f"runs/{run_id}: {state}")
    return code


if __name__ == "__main__":
    raise SystemExit(main())
