"""Small typed wire contracts with generated documentation, not a schema engine.

Only the worker control envelope is migrated here. Domain validators still
validate policy, placement, operation versions and exact task identities.
Descriptive extensions live under ``extensions``; unknown actions or envelope
fields are rejected. Peers with a different executable digest still cannot mix.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Field:
    kind: str
    required: bool = True
    minimum: int | None = None
    maximum: int | None = None
    length: int | None = None

    def check(self, value):
        types = {"string": str, "integer": int, "object": dict}
        # JSON Schema describes mathematical integers, including 1.0. Exact
        # wire-literal checks (e.g. hello major/minor) remain domain checks.
        integer = self.kind == "integer" and (type(value) is int or type(value) is float and value.is_integer())
        if not integer and type(value) is not types[self.kind]:
            return False
        if self.minimum is not None and value < self.minimum:
            return False
        if self.maximum is not None and value > self.maximum:
            return False
        if self.length is not None and not 1 <= len(value) <= self.length:
            return False
        return True

    def schema(self):
        result = {"type": self.kind}
        if self.minimum is not None:
            result["minimum"] = self.minimum
        if self.maximum is not None:
            result["maximum"] = self.maximum
        if self.length is not None:
            result.update(minLength=1, maxLength=self.length)
        return result


IDENTITY = {"session_id": Field("string", length=128), "generation": Field("integer", minimum=1)}
EXTENSIONS = {"extensions": Field("object", required=False)}
CONTROL = {
    "hello": {"major": Field("integer", minimum=1, maximum=1), "minor": Field("integer", minimum=0),
              "nonce": Field("string", length=64), "build_digest": Field("string", length=64), "config": Field("object")},
    # Placement errors may be null; their exact shape remains in placement's
    # existing validator. The contract below deliberately checks names only.
    "placement": {**IDENTITY, "records": None, "error": None},
    "admit": {**IDENTITY, "task": Field("object")},
    "cancel": {**IDENTITY, "id": Field("string", length=128)},
    "ack": {**IDENTITY, "id": Field("string", length=128), "result_digest": Field("string", length=64)},
    "status": {**IDENTITY, "id": Field("string", length=128)},
    "shutdown": dict(IDENTITY),
}


def worker_control(value):
    if not isinstance(value, dict) or not isinstance(value.get("op"), str) or value["op"] not in CONTROL:
        raise ValueError("Unknown worker control operation")
    fields = {**CONTROL[value["op"]], **EXTENSIONS}
    if set(value) - {"op", *fields}:
        raise ValueError("Unknown worker action fields; descriptive additions belong in extensions")
    for name, field in fields.items():
        if field is None:
            continue
        if name not in value:
            if field.required:
                raise ValueError(f"Worker {value['op']} requires {name}")
        elif not field.check(value[name]):
            raise ValueError(f"Worker {value['op']} has invalid {name}")
    return value


def worker_control_schema():
    variants = []
    for operation, fields in CONTROL.items():
        fields = {**fields, **EXTENSIONS}
        variants.append({"type": "object", "properties": {
            "op": {"const": operation}, **{name: field.schema() if field else {} for name, field in fields.items()}},
            "required": ["op", *[name for name, field in fields.items() if field and field.required]],
            "additionalProperties": False})
    return {"$schema": "https://json-schema.org/draft/2020-12/schema",
            "$id": "https://raw.githubusercontent.com/rahel99x/Raven/main/docs/schemas/worker-control.v1.schema.json",
            "title": "Worker control envelope v1", "description": "Generated by raven.protocol_contracts. Transport bounds and domain ownership checks are additional constraints.",
            "oneOf": variants}
