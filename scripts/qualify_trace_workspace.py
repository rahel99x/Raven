#!/usr/bin/env python3
"""Qualify trace workspace source and installed commands without a scheduler.

The retained evidence is generated by the real integrity writer. Scheduling,
sample and GPU records are explicitly synthetic observations used to exercise
the software contract; they never qualify a physical collector or MPI runtime.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TRACE_ACTIONS = ("workspace", "import-activity", "profile", "sample")
COMMANDS = ("raven", "ravenl", "ravenh")


def _request(viewer, target, *, authorized=True, method="GET"):
    from urllib.error import HTTPError
    from urllib.request import Request, urlopen

    headers = {"Authorization": "Bearer " + viewer.token} if authorized else {}
    request = Request(viewer.origin + target, headers=headers, method=method)
    try:
        response = urlopen(request, timeout=3)
    except HTTPError as exc:
        response = exc
    with response:
        raw = response.read((4 << 20) + 1)
        if len(raw) > 4 << 20:
            raise ValueError("Qualification response exceeded its read budget")
        return response.status, json.loads(raw)


def _drain(session, options=None):
    for _ in range(100):
        result = session.refresh(options)
        if result.get("caught_up"):
            return result
    raise ValueError("Qualification fixture did not catch up within 100 bounded reads")


def probe(directory, *, expected_package, source_root=None):
    """Runs inside the selected interpreter, without importing Raven from scripts."""
    if source_root is not None:
        sys.path.insert(0, str(source_root))
    import raven
    from types import SimpleNamespace
    from urllib.error import URLError
    from urllib.request import urlopen

    from raven import layout as L
    from raven.tracing import workspace_ui as UI
    from raven.tracing.activity_import import import_activity
    from raven.tracing.capture import Recorder
    from raven.tracing.workspace_session import WorkspaceSession

    package = Path(raven.__file__).resolve()
    if not package.is_relative_to(expected_package.resolve()):
        raise ValueError(
            "Probe imported Raven outside its selected source/installation"
        )
    directory.mkdir(mode=0o700, parents=True)
    project = directory / "project"
    project.mkdir(mode=0o700)
    with Recorder(
        project,
        job_id="42",
        attempt="qualification",
        cluster="local",
        identity_extra={"rank": 0},
        background_flush=False,
        coverage={
            "adapter": "qualification-fixture",
            "scope": "Synthetic integrity-journal qualification, not hardware or scheduler evidence",
        },
    ) as recorder:
        base = time.monotonic_ns()
        recorder.emit(
            "call",
            {"frame": "f", "function": "qualification_root"},
            thread="one",
            mono_ns=base,
        )
        recorder.emit(
            "activity",
            {
                "activity_kind": "scheduling",
                "name": "fixture on CPU",
                "state": "running",
                "logical_cpu": 1,
                "start_ns": base + 10,
                "end_ns": base + 30,
            },
            thread="one",
            mono_ns=base + 10,
        )
        recorder.emit(
            "cpu_sample",
            {
                "frames": [{"name": "qualification_root"}],
                "event": "fixture-cycles",
                "stack_order": "root-to-leaf",
                "weight": 2,
                "weight_unit": "event-count",
                "logical_cpu": 1,
            },
            thread="one",
            mono_ns=base + 20,
        )
        recorder.emit("return", {"frame": "f"}, thread="one", mono_ns=base + 40)
        recorder.emit(
            "counter",
            {
                "values": {"loss": "0.25"},
                "units": {"loss": "dimensionless"},
                "phase": "qualification",
            },
            thread="one",
            mono_ns=base + 45,
        )
        for offset, phase in ((50, "enter"), (60, "complete")):
            recorder.emit(
                "collective",
                {
                    "communicator": "MPI_COMM_WORLD",
                    "generation": "fixture-world",
                    "sequence": 1,
                    "members": [0],
                    "rank": 0,
                    "operation": "barrier",
                    "phase": phase,
                    "dtype": "byte",
                    "count": 0,
                    "root": 0,
                    "reduction": "sum",
                },
                thread="one",
                mono_ns=base + offset,
            )
    identity = {"job_id": "42", "attempt": "qualification", "cluster": "local"}
    session = WorkspaceSession(
        [recorder.path], expected=identity, index_path=directory / "private.sqlite"
    )
    try:
        result = _drain(
            session,
            {
                "mode": "explore",
                "functions": True,
                "overview": True,
                "metrics": True,
                "samples": True,
                "counters": True,
                "call_tree": True,
            },
        )
        root = next(
            row for row in result["intervals"] if row["name"] == "qualification_root"
        )
        assert root["duration_ns"] == 40
        selected = next(
            row
            for row in result["markers"]
            if row["kind"] == "collective" and row["data"]["phase"] == "complete"
        )
        result = session.refresh(
            {
                "mode": "explore",
                "causal": selected["id"],
                "samples": True,
                "counters": True,
                "call_tree": True,
                "metrics": True,
            }
        )
        assert result["causal"]["edges"] and not result["causal"]["cycles"]
        assert result["samples"]["observations"] == 1
        assert result["samples"]["groups"][0]["inclusive_share"] == 1
        assert result["counters"]["series"][0]["points"][0]["value"] == "0.25"
        assert result["call_tree"]["nodes"]
        cpu = session.refresh(
            {"mode": "explore", "logical_cpu": 1, "perspective": "cpu"}
        )
        assert any(
            row["kind"] == "cpu_stack_slice" and row["duration_ns"] == 20
            for row in cpu["workspace_projection"]["intervals"]
        )
        before_limit = session.index.query(kind="python", thread="one", limit=1)
        assert [row["id"] for row in before_limit["intervals"]] == [root["id"]]
        bounds = result["bounds"][0]
        context = {
            "schema": "raven.trace-resource-context/v1",
            "identity": identity,
            "provenance": "Synthetic source-scoped allocation declaration for software qualification",
            "epochs": [
                {
                    "clock_id": bounds["clock_id"],
                    "start_ns": bounds["start_ns"],
                    "end_ns": bounds["end_ns"],
                    "logical_cpu_count": 2,
                    "unit": "logical-cpu",
                    "coverage_complete": True,
                    "gpu_coverage_complete": False,
                    "source_ids": [result["sources"][0]["id"]],
                    "provenance": "Fixture denominator",
                }
            ],
        }
        session.set_capacity(context)
        result = session.refresh({"mode": "explore", "metrics": True})
        utilization = next(
            row
            for row in result["metrics"]["metrics"]
            if row["name"] == "cpu_allocation_utilization"
        )
        assert utilization["value"] is not None and 0 < utilization["value"] <= 1
        state = {}
        UI.publish(state, result)
        owner = SimpleNamespace(say=lambda message: None, save=lambda: None)
        assert UI.command(owner, state, ["event", root["id"]])
        rows, _ = UI.render(SimpleNamespace(g=L.Glyphs(True)), state, "42", 80)
        text = "\n".join(L.row_text(row) for row in rows)
        assert "qualification_root" in text
        assert all(L.vlen(L.row_text(row)) <= 80 for row in rows)
        assert session.path.stat().st_mode & 0o077 == 0
        viewer = session.open_browser()
        with urlopen(viewer.origin + "/", timeout=3) as page:
            document = page.read((256 << 10) + 1)
            assert len(document) <= 256 << 10
            assert (
                b"Raven Trace Workspace" in document
                and b"qualification_root" not in document
            )
            assert "script-src 'sha256-" in page.headers["Content-Security-Policy"]
        assert _request(viewer, "/api/catalog", authorized=False)[0] == 401
        status, data = _request(viewer, "/api/query?kind=python&limit=1")
        assert status == 200 and data["result"]["intervals"][0]["id"] == root["id"]
        assert _request(viewer, "/api/catalog", method="POST")[0] == 405
        origin = viewer.origin
        viewer.close()
        assert session.index.detail(root["id"])["id"] == root["id"]
        try:
            urlopen(origin + "/", timeout=1)
        except (URLError, OSError):
            pass
        else:
            raise ValueError("Closed qualification viewer remained accessible")
    finally:
        session.close()
    with_session = WorkspaceSession(
        [recorder.path], expected=identity, index_path=directory / "private.sqlite"
    )
    try:
        assert not with_session.index.query()["intervals"], (
            "Reopened derived rows escaped integrity revalidation"
        )
        rebuilt = _drain(with_session, {"mode": "explore"})
        assert any(row["id"] == root["id"] for row in rebuilt["intervals"])
    finally:
        with_session.close()
    report = directory / "activities.json"
    report.write_text(
        json.dumps(
            {
                "traceEvents": [
                    {
                        "ph": "X",
                        "ts": 10,
                        "dur": 3,
                        "cat": "kernel",
                        "name": "fixture_kernel",
                        "pid": 1,
                        "tid": 2,
                        "args": {
                            "node": "fixture-node",
                            "device": 0,
                            "device_uuid": "GPU-fixture",
                            "stream": 1,
                        },
                    }
                ]
            }
        )
    )
    imported = import_activity(
        report, project=project, job_id="43", attempt="fixture-import", cluster="local"
    )
    imported_session = WorkspaceSession(
        [imported["manifest"]], index_path=directory / "import.sqlite"
    )
    try:
        projected = _drain(imported_session, {"mode": "explore", "perspective": "gpu"})[
            "workspace_projection"
        ]
        assert projected["intervals"][0]["kind"] == "gpu_kernel"
        assert projected["intervals"][0]["duration_ns"] == 3000
    finally:
        imported_session.close()
    return {
        "package": str(package),
        "manifest": str(recorder.path),
        "activity_input": str(report),
        "project": str(project),
        "interval_id": root["id"],
        "terminal_columns": 80,
        "checks": [
            "verified-journal",
            "indexed-range",
            "before-limit-filters",
            "cpu-stack-intersection",
            "sample-share",
            "scientific-counter",
            "MPI-protocol-parse",
            "owner-capacity",
            "terminal-render",
            "private-http-document",
            "private-http-auth",
            "readonly-http",
            "viewer-close",
            "index-revalidation",
            "portable-activity-import",
        ],
        "hardware_qualified": False,
        "scheduler_calls": 0,
    }


def qualify(*, wheel=None, installed_python=None):
    import importlib.util

    specification = importlib.util.spec_from_file_location(
        "raven_trace_qualification_runner", ROOT / "scripts" / "qualify_flagship.py"
    )
    owner = importlib.util.module_from_spec(specification)
    specification.loader.exec_module(owner)
    run = owner.run

    checks = []

    def check(name, callback):
        started = time.monotonic()
        try:
            evidence = callback()
            checks.append(
                {
                    "id": name,
                    "status": "qualified",
                    "seconds": round(time.monotonic() - started, 3),
                    "evidence": evidence,
                }
            )
            return evidence
        except Exception as exc:
            checks.append(
                {
                    "id": name,
                    "status": "failed",
                    "seconds": round(time.monotonic() - started, 3),
                    "detail": str(exc)[:2400],
                }
            )
            return None

    with tempfile.TemporaryDirectory(prefix="raven-trace-qualification-") as temporary:
        scratch = Path(temporary)
        config = scratch / "config.json"
        config.write_text('{"startup_animation":false,"animations":false}\n')
        audit, tools = scratch / "scheduler-attempts.txt", scratch / "scheduler-stubs"
        tools.mkdir(mode=0o700)
        for name in (
            "salloc",
            "sbatch",
            "srun",
            "squeue",
            "sacct",
            "scontrol",
            "scancel",
            "sstat",
        ):
            path = tools / name
            path.write_text(
                '#!/bin/sh\nprintf \'%s\\n\' "$0" >> "$RAVEN_QUALIFY_SCHEDULER_AUDIT"\nexit 97\n'
            )
            path.chmod(0o700)
        env = {
            key: value
            for key, value in os.environ.items()
            if not key.startswith("SLURM_")
        }
        env.update(
            PYTHONPATH="",
            PYTHONNOUSERSITE="1",
            XDG_CONFIG_HOME=str(scratch / "config"),
            XDG_STATE_HOME=str(scratch / "state"),
            RAVEN_CONFIG=str(config),
            RAVEN_QUALIFY_SCHEDULER_AUDIT=str(audit),
            PATH=str(tools) + os.pathsep + os.environ.get("PATH", ""),
        )
        driver = Path(__file__).resolve()
        source = check(
            "source-workspace",
            lambda: json.loads(
                run(
                    [
                        sys.executable,
                        "-I",
                        driver,
                        "--probe",
                        str(scratch / "source"),
                        "--source-root",
                        ROOT,
                        "--expected-package",
                        ROOT,
                    ],
                    cwd=scratch,
                    env=env,
                    timeout=30,
                )
            ),
        )
        if wheel is not None:

            def install():
                if (
                    not wheel.is_file()
                    or wheel.suffix != ".whl"
                    or wheel.stat().st_size > 64 << 20
                ):
                    raise ValueError(
                        "Expected a locally built wheel smaller than 64 MiB"
                    )
                target = scratch / "installed"
                run(
                    [sys.executable, "-m", "venv", target],
                    cwd=scratch,
                    env=env,
                    timeout=60,
                )
                python = target / "bin" / "python"
                run(
                    [python, "-m", "pip", "install", "--no-index", "--no-deps", wheel],
                    cwd=scratch,
                    env=env,
                    timeout=60,
                )
                return {
                    "python": str(python),
                    "wheel_sha256": hashlib.sha256(wheel.read_bytes()).hexdigest(),
                    "dependencies_installed": False,
                }

            installation = check("install-local-wheel-offline", install)
            installed_python = Path(installation["python"]) if installation else None
        if installed_python is not None:
            prefix = installed_python.parent.parent
            installed = check(
                "installed-workspace",
                lambda: json.loads(
                    run(
                        [
                            installed_python,
                            "-I",
                            driver,
                            "--probe",
                            str(scratch / "wheel"),
                            "--expected-package",
                            prefix,
                        ],
                        cwd=scratch,
                        env=env,
                        timeout=30,
                    )
                ),
            )

            def commands():
                if installed is None:
                    raise ValueError(
                        "Installed probe failed; no fixture is available for command qualification"
                    )
                helps, queries = [], []
                for name in COMMANDS:
                    executable = installed_python.parent / name
                    if not executable.is_file():
                        raise ValueError(
                            "Installed console command is missing: " + name
                        )
                    for action in TRACE_ACTIONS:
                        output = run(
                            [executable, "trace", action, "--help"],
                            cwd=scratch,
                            env=env,
                        )
                        if "usage:" not in output.lower():
                            raise ValueError(
                                "No command help for " + name + " trace " + action
                            )
                        helps.append(name + " trace " + action)
                    output = run(
                        [
                            executable,
                            "trace",
                            "workspace",
                            installed["manifest"],
                            "--index",
                            scratch / (name + ".sqlite"),
                            "--json",
                            "--functions",
                            "--samples",
                            "--counters",
                        ],
                        cwd=scratch,
                        env=env,
                    )
                    value = json.loads(output)
                    if not any(
                        row["name"] == "qualification_root"
                        for row in value["intervals"]
                    ):
                        raise ValueError(
                            "Installed workspace command did not read the exact retained fixture"
                        )
                    queries.append(name)
                imported = json.loads(
                    run(
                        [
                            installed_python.parent / "raven",
                            "trace",
                            "import-activity",
                            installed["activity_input"],
                            "--project",
                            installed["project"],
                            "--job-id",
                            "44",
                            "--attempt",
                            "cli-import",
                        ],
                        cwd=scratch,
                        env=env,
                    )
                )
                if not Path(imported["manifest"]).is_file():
                    raise ValueError(
                        "Installed activity import did not publish its verified manifest"
                    )
                page = run(
                    [
                        installed_python.parent / "raven",
                        "--fake",
                        "--no-state",
                        "--no-plugins",
                        "--once",
                        "--tab",
                        "traces",
                        "--ascii",
                        "--no-color",
                    ],
                    cwd=scratch,
                    env=env,
                )
                if not page.strip() or not page.isascii() or "\x1b" in page:
                    raise ValueError(
                        "Installed Traces destination did not render clean plain-text output"
                    )
                return {
                    "help": helps,
                    "retained_queries": queries,
                    "activity_import": True,
                    "global_traces_destination": True,
                    "outside_checkout": True,
                    "isolated_probe_python": True,
                }

            check("installed-console-commands", commands)
        else:
            checks.append(
                {
                    "id": "installed-workspace",
                    "status": "untested",
                    "detail": "Supply --wheel PATH or --installed-python PATH",
                }
            )

        def no_scheduler():
            if audit.exists():
                raise ValueError(
                    "Offline trace qualification attempted scheduler commands"
                )
            return {"attempts": []}

        check("no-scheduler-attempts", no_scheduler)
    return {
        "schema": "raven.trace-workspace-qualification/v1",
        "status": "failed"
        if any(row["status"] == "failed" for row in checks)
        else "qualified-for-recorded-checks",
        "python": platform.python_version(),
        "platform": platform.platform(),
        "production_qualified": False,
        "scope": "Local source and isolated installed software paths; real verified journals and explicitly synthetic execution observations",
        "unqualified": [
            "live scheduler",
            "multi-node execution",
            "physical CPU sampling",
            "physical GPU activity",
            "hardware control flow",
            "real MPI",
            "remote transport",
        ],
        "source_fixture_available": source is not None,
        "checks": checks,
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    install = parser.add_mutually_exclusive_group()
    install.add_argument("--wheel", type=Path)
    install.add_argument("--installed-python", type=Path)
    parser.add_argument("--probe", type=Path, help=argparse.SUPPRESS)
    parser.add_argument("--source-root", type=Path, help=argparse.SUPPRESS)
    parser.add_argument("--expected-package", type=Path, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    if args.probe:
        if not args.expected_package:
            parser.error("Internal probe requires its expected package prefix")
        print(
            json.dumps(
                probe(
                    args.probe,
                    expected_package=args.expected_package,
                    source_root=args.source_root,
                ),
                allow_nan=False,
            )
        )
        return 0
    if args.output is None or args.output.exists():
        parser.error("Choose a new --output JSON report path")
    value = qualify(
        wheel=args.wheel.resolve() if args.wheel else None,
        installed_python=args.installed_python.absolute()
        if args.installed_python
        else None,
    )
    descriptor = os.open(args.output, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, "w", encoding="utf-8") as stream:
        json.dump(value, stream, ensure_ascii=True, allow_nan=False, indent=2)
        stream.write("\n")
    print(value["status"] + ": " + str(args.output))
    return int(value["status"] == "failed")


if __name__ == "__main__":
    raise SystemExit(main())
