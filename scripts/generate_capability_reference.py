#!/usr/bin/env python3
"""Generate the canonical proposal ownership map; --check rejects stale output."""
from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from raven.capabilities import AREAS, PROPOSALS, for_area, validate

DEFAULT_OUTPUT = ROOT / "docs" / "reference" / "capabilities.md"


def cell(value):
    return str(value).replace("|", "&#124;").replace("\r", " ").replace("\n", " ")


def render():
    lines = [
        "# Capability ownership and proposal map", "",
        "Generated by `python3 scripts/generate_capability_reference.py` from",
        "`raven.capabilities`. Do not edit this file by hand. Use `--check` to",
        "validate the installed operation references and detect stale documentation.", "",
        "The 56 proposal entries have **eight primary owning areas**. Each original",
        "entry occurs once in the ownership tables. Related IDs and repeated operation",
        "names are overlap references, not additional features or implementations.", "",
        "`F01`–`F40` retain the numbered investments in the",
        "[flagship dossier](../research/flagship-strategy.md). `R1`–`R5` retain its",
        "research hypotheses. `V5-TRACE` names the earlier tracing proposal; `V6-01`–",
        "`V6-10` assign stable IDs to the ten named proposals in the order recorded in",
        "the [implementation ledger](../FLAGSHIP_IMPLEMENTATION.md). These reference",
        "IDs do not rename commands, operation keys, saved settings, or schemas.", "",
        "**Supported** means a mechanism exists within its stated scope. **Partial**",
        "retains an explicit unimplemented part of the original ambition. **Procedure**",
        "means a protocol or documentation exists but the external activity has not",
        "been completed. These labels preserve the ledger's conservative delivery",
        "assessment; ownership consolidation does not certify an entire proposal.", "",
        "Qualification gates remain separate: **site** requires target-system evidence;",
        "**research** requires an independent scientific evaluation; **external-users**",
        "requires actual adoption/usability work; **maintenance** requires ongoing",
        "maintained releases. An empty gate field does not remove the stated boundary.", "",
        "## Ownership totals", "",
        "| Owning area | Original entries | Responsibility |",
        "| --- | ---: | --- |",
    ]
    for area in AREAS:
        lines.append(f"| {area.title} | {len(for_area(area.key))} | {cell(area.responsibility)} |")
    counts = Counter(item.delivery for item in PROPOSALS)
    lines += ["", f"Total: **{len(PROPOSALS)} entries** ({counts['supported']} supported within scope, "
              f"{counts['partial']} partial, {counts['procedure']} procedures). These are entry statuses, "
              "not a distinct-feature completion percentage.", ""]
    for area in AREAS:
        lines += ["## " + area.title, "", "Owner key: `" + area.key + "`.", "",
                  "| Original ID / proposal | Delivery / gates | Installed operations | Supported mechanism | Remaining boundary | Related entries |",
                  "| --- | --- | --- | --- | --- | --- |"]
        for item in for_area(area.key):
            operations = ", ".join("`" + key + "`" for key in item.operations) or "Core UI, infrastructure, or documentation"
            gates = item.delivery + (" / " + ", ".join(item.gates) if item.gates else "")
            related = ", ".join(item.related) or "—"
            lines.append(f"| {item.id} — {cell(item.title)} | {gates} | {operations} | {cell(item.scope)} | {cell(item.boundary)} | {related} |")
        lines.append("")
    lines += [
        "## Runtime lookup and compatibility", "",
        "`raven.capabilities.lookup(reference)` returns one immutable proposal descriptor.",
        "`for_area(key)` returns the original entries owned by that area.",
        "`for_operation(key)` returns every proposal that refers to an installed operation.",
        "These lookups read prebuilt metadata indexes; they do not import adapters, start",
        "collectors, execute commands, add menus, or change saved UI state.", "",
        "```python",
        "from raven.capabilities import lookup, for_area, for_operation",
        "",
        'lookup("F22").area  # "investigation"',
        'lookup("22") is lookup("flagship-22")  # Stable aliases for F22',
        'for_operation("causal-delay")  # V6-01 and F22 refer to the same operation',
        'for_area("experiments")  # Each owned proposal appears once',
        "```", "",
        "Canonical IDs and area keys are case-insensitive; surrounding whitespace is",
        "ignored. Unknown proposal/area references raise `ValueError`. An operation",
        "without an association returns an empty tuple; it is not declared unsupported.", "",
        "Additional stable aliases: two-digit IDs and `flagship-NN` for F entries;",
        "`research-N` for R entries; `stack-tracing` for V5-TRACE; and the following",
        "original v6 names. These are metadata aliases, not new terminal commands.", "",
        "| Original v6 ID | Stable named alias |", "| --- | --- |",
    ]
    for item in PROPOSALS:
        if item.id.startswith("V6-"):
            lines.append(f"| {item.id} | `{'`, `'.join(item.aliases)}` |")
    lines += ["", "Run `python3 scripts/generate_capability_reference.py --check` after editing",
              "descriptors. Validation rejects missing/duplicate original entries, unknown",
              "owners or operation keys, ambiguous aliases, and broken overlap references.", ""]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    errors = validate()
    if errors:
        print("Invalid capability catalog:\n" + "\n".join(errors), file=sys.stderr)
        return 2
    content = render()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != content:
            print("Capability reference is stale. Run scripts/generate_capability_reference.py.", file=sys.stderr)
            return 1
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8")
    print(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
