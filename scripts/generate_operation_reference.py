#!/usr/bin/env python3
"""Generate operation fields and task controls from their executable descriptors."""
from __future__ import annotations

import argparse
import html
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tower.flagship_commands import command_rows
from tower.operations import catalog

DEFAULT_OUTPUT = ROOT / "docs" / "reference" / "operations.md"


def cell(value):
    """Keep descriptor text inside one Markdown table cell."""
    text = value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)
    return html.escape(text, quote=False).replace("|", "&#124;").replace("\r", " ").replace("\n", " ").replace("`", "&#96;")


def code(value):
    return "<code>" + cell(value) + "</code>"


def render(specifications=None, tasks=None):
    specifications = catalog() if specifications is None else specifications
    tasks = command_rows() if tasks is None else tasks
    lines = [
        "# Operation controls and fields", "",
        "Generated by `python3 scripts/generate_operation_reference.py` from the same",
        "operation specifications and task descriptors used by the interface. Do not",
        "edit this file by hand. Run the generator with `--check` to detect stale fields.", "",
        "Open `:workbench all` for every operation, or use a task below. Opening a form",
        "does not execute it. `:ops KEY` opens one form; `:ops run KEY field=value`",
        "inspects explicit inputs. Quote values that contain spaces. **Inspect / prepare**",
        "collects evidence or prepares a plan. When an action is available, inspect its",
        "scope with **Review action**, then use **Confirm apply**. A field can have",
        "additional identity, path, schema or applicability checks in its feature guide.", "",
        "Use `:ops cancel` to cancel inspection, `:ops form` to edit inputs,",
        "`:ops copy` to copy a report, and `:ops close` to leave the workbench.", "",
        "See [review and recovery rules](../guides/operations.md#review-background-work-and-recovery-rules),",
        "[feature scope](../FLAGSHIP_IMPLEMENTATION.md), and [all controls](../CONTROLS.md).", "",
        "## Task controls", "",
        "| Task | Command | Purpose |", "| --- | --- | --- |",
    ]
    for task in tasks:
        lines.append(f"| {cell(task['label'])} | {code(':' + task['command'])} | {cell(task['description'])} |")
    lines += ["| Pinned | `:workbench pinned` | Show saved operation shortcuts with current selection context. |",
              "| All | `:workbench all` | Show the complete operation catalog. |", "",
              f"## Operations ({len(specifications)})", "",
              "Required fields are required by the form. A blank default means an empty input;",
              "the operation can require further values for a selected action. Choices are",
              "literal values accepted by the interface.", ""]
    for specification in sorted(specifications, key=lambda item: (item.get("group", ""), item["key"])):
        lines += ["### " + cell(specification["title"]), "",
                  f"Command: {code(':ops ' + specification['key'])}. Group: {cell(specification.get('group', ''))}.", "",
                  cell(specification.get("summary", "")), "",
                  "| Field | Label | Required | Default | Choices |",
                  "| --- | --- | --- | --- | --- |"]
        for field in specification.get("fields", []):
            default = field.get("default", "")
            choices = ", ".join(code(value) for value in field.get("choices", [])) or "—"
            lines.append(f"| {code(field['key'])} | {cell(field['label'])} | {'Yes' if field.get('required') else 'No'} | {code(default) if default != '' else '(blank)'} | {choices} |")
        if not specification.get("fields"):
            lines.append("| — | No input fields | — | — | — |")
        lines.append("")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="Check without writing the reference")
    args = parser.parse_args(argv)
    content = render()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != content:
            print("Operation reference is stale. Run scripts/generate_operation_reference.py.", file=sys.stderr)
            return 1
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8")
    print(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
